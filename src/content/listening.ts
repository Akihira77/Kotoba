import type { JLPTLevel, ListeningItem, ListeningLine, QuizQuestion, ReadingVocab } from "@/lib/types";

type Speaker = "A" | "B" | "Narasi";
type LineRow = [speaker: Speaker, jp: string, reading: string];
type PhraseRow = [jp: string, reading: string, meaning: string];
type QuestionRow = [prompt: string, options: string[], answerIndex: number, explanation: string, audioText?: string];

function toPhrases(rows: PhraseRow[]): ReadingVocab[] {
  return rows.map(([jp, reading, meaning]) => ({ jp, reading, meaning }));
}

function toLines(itemId: string, rows: LineRow[]): ListeningLine[] {
  return rows.map(([speaker, jp, reading], index) => ({
    id: `${itemId}-${index + 1}`,
    speaker,
    jp,
    reading,
  }));
}

function toQuestions(itemId: string, level: JLPTLevel, rows: QuestionRow[]): QuizQuestion[] {
  return rows.map(
    ([prompt, options, answerIndex, explanation, audioText], index): QuizQuestion => ({
      id: `${itemId}-q${index + 1}`,
      type: "listening",
      level,
      prompt,
      options,
      answerIndex,
      explanation,
      audioText,
      sourceId: itemId,
      section: "choukai",
    }),
  );
}

function listening(
  id: string,
  level: JLPTLevel,
  title: string,
  titleId: string,
  scenario: string,
  lineRows: LineRow[],
  questionRows: QuestionRow[],
  phraseRows: PhraseRow[],
): ListeningItem {
  return {
    id,
    level,
    title,
    titleId,
    scenario,
    lines: toLines(id, lineRows),
    questions: toQuestions(id, level, questionRows),
    keyPhrases: toPhrases(phraseRows),
  };
}

